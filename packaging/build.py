#!/usr/bin/env python3
"""Build the per-agent packages in plugins/ from the two sources, server/ and skill/.

    python packaging/build.py           # (re)write plugins/ and the marketplace files
    python packaging/build.py --check   # exit 1 if any generated file is stale

Each plugin bundles its own copy of the server, so it runs wherever the agent installs it:
the MCP command is `uv run --project <plugin root>/server spedas-tplot-mcp`.
Claude Code: ${CLAUDE_PLUGIN_ROOT} in args, started in the session directory.
Codex: "cwd": "." (the plugin root) with a relative --project, the pattern Codex's own plugins use.
"""

from __future__ import annotations

import argparse
import filecmp
import json
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SERVER = ROOT / "server"
SKILL = ROOT / "skill" / "spedas-tplot"
OUT = ROOT / "plugins"

NAME = "spedas-tplot"
SERVER_NAME = "spedas-tplot"
DESCRIPTION = ("PySPEDAS tplot for agents: load space-physics mission data into tplot variables, "
               "inspect, transform and plot them, and get a replayable PySPEDAS script.")
KEYWORDS = ["spedas", "pyspedas", "tplot", "heliophysics", "space-physics", "magnetosphere", "mcp"]
REPO = "https://github.com/spedas/spedas-plugin"
AUTHOR = {"name": "Zesen Huang", "url": REPO}
LICENSE = "MIT"
# Variables the server reads; Codex only passes listed variables to MCP servers.
ENV_VARS = ["SPEDAS_DATA_DIR", "SPEDAS_TPLOT_OUTPUT_DIR", "SPEDAS_TPLOT_ALLOW_EXEC", "PYSPEDAS_CONFIG_FILE",
            "SPEDAS_TPLOT_WEB", "SPEDAS_TPLOT_WEB_PORT"]
SERVER_FILES = ["pyproject.toml", "uv.lock", ".python-version", "README.md", "src"]


def version() -> str:
    for line in (SERVER / "pyproject.toml").read_text().splitlines():
        if line.startswith("version"):
            return line.split("=", 1)[1].strip().strip('"')
    raise SystemExit("no version in server/pyproject.toml")


def uv_command(root_var: str) -> dict:
    return {"command": "uv", "args": ["run", "--quiet", "--project", f"{root_var}/server", "spedas-tplot-mcp"]}


def copy_server(dest: Path) -> None:
    dest.mkdir(parents=True, exist_ok=True)
    for name in SERVER_FILES:
        src = SERVER / name
        if src.is_dir():
            copytree_into(src, dest / name)
        else:
            shutil.copy2(src, dest / name)


def copy_skill(dest: Path) -> None:
    copytree_into(SKILL, dest)


def write_json(path: Path, data: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2) + "\n")


def plugin_readme(agent: str, install: str) -> str:
    return f"""# {NAME} for {agent}

Generated by `packaging/build.py` from `server/` and `skill/`; edit those, not this folder.

{DESCRIPTION}

## Install

{install}

## Needs

- [`uv`](https://docs.astral.sh/uv/) on `PATH`. The first start creates `server/.venv` and
  installs PySPEDAS, which can take a minute; later starts are fast.
- Network access to the mission data servers (CDAWeb, MMS SDC, ...).

## Settings (environment variables)

| Variable | Default | Meaning |
|---|---|---|
| `SPEDAS_DATA_DIR` | `~/spedas_data` (or your PySPEDAS preferences file) | where downloaded data files are kept |
| `SPEDAS_TPLOT_OUTPUT_DIR` | `./spedas_tplot_output` (`~/spedas_tplot_output` when started outside a workspace) | plots, exports, session script; the agent can also call `set_output_dir` |
| `SPEDAS_TPLOT_ALLOW_EXEC` | off | `1` adds the `run_python` tool (runs code in the server process) |
| `SPEDAS_TPLOT_WEB` | on | `0` turns off the web workbench |
| `SPEDAS_TPLOT_WEB_PORT` | 8765 | first port to try for the workbench (the next free one is used) |

## Web workbench

While the agent is connected, the same tplot session is open in the browser at
http://127.0.0.1:8765/ (ask the agent for `status` if that port was taken). You see what the
agent loads and plots, live, and can zoom, stack panels, load data and run functions yourself.
"""


def build_claude(dest: Path) -> None:
    write_json(dest / ".claude-plugin" / "plugin.json", {
        "name": NAME, "version": version(), "description": DESCRIPTION, "author": AUTHOR,
        "license": LICENSE, "keywords": KEYWORDS,
    })
    write_json(dest / ".mcp.json", {"mcpServers": {SERVER_NAME: uv_command("${CLAUDE_PLUGIN_ROOT}")}})
    copy_skill(dest / "skills" / NAME)
    copy_server(dest / "server")
    (dest / "README.md").write_text(plugin_readme("Claude Code", """```
/plugin marketplace add spedas/spedas-plugin
/plugin install spedas-tplot@spedas-plugin
```

Restart Claude Code, then `/mcp` should list `spedas-tplot`. To pre-install the Python environment
(avoids a slow first start): `uv sync --project ~/.claude/plugins/cache/<...>/spedas-tplot/server`."""))


def build_codex(dest: Path) -> None:
    write_json(dest / ".codex-plugin" / "plugin.json", {
        "name": NAME, "version": version(), "description": DESCRIPTION, "author": AUTHOR,
        "license": LICENSE, "keywords": KEYWORDS,
        "skills": "./skills/", "mcpServers": "./.mcp.json",
        "interface": {
            "displayName": "SPEDAS tplot",
            "shortDescription": "Load, transform and plot space-physics data with PySPEDAS tplot",
            "longDescription": DESCRIPTION,
            "developerName": AUTHOR["name"],
            "category": "Research",
            "capabilities": ["Read", "Write"],
            "defaultPrompt": [
                "Plot OMNI IMF Bz, solar wind speed and SYM-H for 2015-10-16",
                "Load THEMIS-A FGM for 2015-10-16 08:00-09:00 and plot B in GSM",
                "Show the MMS1 ion energy spectrogram and density for 2015-10-16 13:00-13:10",
            ],
        },
    })
    # Codex's own stdio plugins start in the plugin root ("cwd": ".") with relative paths; the
    # server then defaults its output to ~/spedas_tplot_output (see runtime._default_output_dir).
    server = {"command": "uv", "args": ["run", "--quiet", "--project", "./server", "spedas-tplot-mcp"], "cwd": "."}
    server["env_vars"] = ENV_VARS
    server["startup_timeout_sec"] = 300  # the first start installs PySPEDAS into server/.venv
    write_json(dest / ".mcp.json", {"mcpServers": {SERVER_NAME: server}})
    copy_skill(dest / "skills" / NAME)
    copy_server(dest / "server")
    (dest / "README.md").write_text(plugin_readme("Codex", """```
codex plugin marketplace add spedas/spedas-plugin
codex plugin add spedas-tplot@spedas-plugin
```

Or open `/plugins` inside Codex and install it from the `spedas-plugin` marketplace."""))


def build_generic(dest: Path) -> None:
    """A skill folder plus MCP config snippets for clients without a plugin system."""
    copy_skill(dest / "skills" / NAME)
    local = {"command": "uv", "args": ["run", "--quiet", "--project", "/ABSOLUTE/PATH/TO/spedas-plugin/server", "spedas-tplot-mcp"]}
    write_json(dest / "mcp.json", {"mcpServers": {SERVER_NAME: local}})
    (dest / "codex-config.toml").write_text(
        f"[mcp_servers.{SERVER_NAME}]\n"
        f'command = "uv"\n'
        f'args = {json.dumps(local["args"])}\n'
        f"env_vars = {json.dumps(ENV_VARS)}\n"
        f"startup_timeout_sec = 300\n"
    )
    (dest / "README.md").write_text(f"""# {NAME}: generic MCP server + skill

Generated by `packaging/build.py`; edit `server/` and `skill/`, not this folder.

For any MCP client (Claude Desktop, Cursor, Windsurf, OpenCode, Gemini CLI, LingTai, ...), and for
Codex or Claude Code when you would rather not use their plugin systems.

## 1. The MCP server

Replace `/ABSOLUTE/PATH/TO/spedas-plugin` with where this repo is checked out, then:

- JSON clients (Claude Desktop `claude_desktop_config.json`, Cursor `.cursor/mcp.json`, Claude Code
  `.mcp.json`, ...): merge `mcp.json` into the client's MCP config.
- Codex without the plugin: append `codex-config.toml` to `~/.codex/config.toml`.
- Claude Code one-liner: `claude mcp add {SERVER_NAME} -- uv run --quiet --project /ABSOLUTE/PATH/TO/spedas-plugin/server spedas-tplot-mcp`

Needs `uv` on `PATH`. Run `uv sync --project /ABSOLUTE/PATH/TO/spedas-plugin/server` once first
so the client does not time out while PySPEDAS installs.

## 2. The skill

Copy or symlink `skills/{NAME}` into the agent's skill folder: `~/.claude/skills/` (Claude Code),
`~/.codex/skills/` (Codex), `~/.agents/skills/` (other agents). Agents without a skill loader can
read `skills/{NAME}/SKILL.md` directly (point their system prompt or AGENTS.md at it).
""")


def build_marketplaces(dest_root: Path) -> None:
    write_json(dest_root / ".claude-plugin" / "marketplace.json", {
        "name": "spedas-plugin",
        "owner": AUTHOR,
        "metadata": {"description": "SPEDAS tools for coding agents"},
        "plugins": [{"name": NAME, "source": f"./plugins/claude-code/{NAME}", "description": DESCRIPTION,
                     "version": version(), "keywords": KEYWORDS}],
    })
    write_json(dest_root / ".agents" / "plugins" / "marketplace.json", {
        "name": "spedas-plugin",
        "interface": {"displayName": "SPEDAS"},
        "plugins": [{"name": NAME, "source": {"source": "local", "path": f"./plugins/codex/{NAME}"},
                     "policy": {"installation": "AVAILABLE", "authentication": "ON_INSTALL"},
                     "category": "Research"}],
    })


def build_all(root: Path) -> None:
    out = root / "plugins"
    build_claude(out / "claude-code" / NAME)
    build_codex(out / "codex" / NAME)
    build_generic(out / "generic")
    build_marketplaces(root)


GENERATED = ["plugins", ".claude-plugin/marketplace.json", ".agents/plugins/marketplace.json"]


def diff_trees(a: Path, b: Path) -> list[str]:
    if a.is_file() or b.is_file():
        return [] if a.is_file() and b.is_file() and filecmp.cmp(a, b, shallow=False) else [str(b)]
    cmp = filecmp.dircmp(a, b, ignore=["__pycache__", ".venv", ".DS_Store"])
    bad = [str(b / n) for n in cmp.left_only + cmp.right_only + cmp.funny_files]
    bad += [str(b / n) for n in cmp.common_files if not filecmp.cmp(a / n, b / n, shallow=False)]
    for sub in cmp.common_dirs:
        bad += diff_trees(a / sub, b / sub)
    return bad


def clean(out: Path) -> None:
    """Empty plugins/ but keep each server/.venv: a local marketplace runs the plugin in place,
    so deleting the venv would break a server that is running from it."""
    if not out.exists():
        return
    for path in sorted(out.rglob("*"), key=lambda q: len(q.parts), reverse=True):
        if ".venv" in path.relative_to(out).parts:
            continue
        if path.is_dir():
            if not any(path.iterdir()):
                path.rmdir()
        else:
            path.unlink()


def copytree_into(src: Path, dest: Path) -> None:
    shutil.copytree(src, dest, ignore=shutil.ignore_patterns("__pycache__", "*.pyc", ".DS_Store"), dirs_exist_ok=True)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="verify plugins/ is up to date; write nothing")
    a = ap.parse_args()
    if not (SERVER / "uv.lock").exists():
        raise SystemExit("server/uv.lock missing: run `uv lock` in server/ first")
    if a.check:
        with tempfile.TemporaryDirectory() as tmp:
            build_all(Path(tmp))
            stale = []
            for rel in GENERATED:
                if not (ROOT / rel).exists():
                    stale.append(rel)
                else:
                    stale += diff_trees(Path(tmp) / rel, ROOT / rel)
        if stale:
            print("stale generated files (run packaging/build.py):\n  " + "\n  ".join(stale))
            return 1
        print("plugins/ is up to date")
        return 0
    clean(OUT)
    build_all(ROOT)
    print(f"built {OUT.relative_to(ROOT)}/{{claude-code,codex,generic}} and the marketplace files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
